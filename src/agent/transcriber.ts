/**
 * Transcriber — writes Argus's reasoning onto the PR so reviewers can follow it.
 *
 * Everything goes into a single transcript comment with collapsible sections
 * (one comment per step used to cost up to eight writes per PR against the
 * hourly comment budget). All model-written text passes through
 * {@link neutralizeModelText}: it is derived from untrusted input and must not
 * be able to ping people or hide content in HTML comments.
 */

import type { Forge } from '../forge/types';
import type { IssueEvaluation, CodingIteration, TrackedIssue, PRAnalysis, SynthesisCandidate } from './types';
import type { InvestigationResult } from './investigator';
import type { StampManager } from '../crypto/stamp';
import { artifactId } from '../crypto/stamp';
import type { Logger } from '../util/logger';
import { inlineCode, neutralizeModelText as safe, oneLine, truncate } from '../util/text';

/** GitHub rejects comments over 65,536 characters; leave room for the stamp. */
const MAX_COMMENT_CHARS = 60_000;

const CI_LABEL: Record<NonNullable<CodingIteration['ciResult']>, string> = {
    passing: '✅ passing',
    failing: '❌ failing',
    pending: '⏳ did not finish',
    none: '➖ no CI configured',
};

export class Transcriber {
    constructor(
        private readonly logger: Logger,
        private readonly stampManager: StampManager,
    ) {}

    /** Post the full reasoning transcript for a new PR as one comment. */
    async postTranscript(
        forge: Forge,
        prNumber: number,
        issue: TrackedIssue,
        evaluation: IssueEvaluation,
        investigation: InvestigationResult,
        iterations: CodingIteration[],
    ): Promise<void> {
        const last = iterations[iterations.length - 1];
        const sections = [
            `## 🤖 Argus transcript for #${issue.issueNumber}`,
            '',
            '| | |',
            '|---|---|',
            `| **Category / severity** | ${evaluation.category} / ${evaluation.severity} |`,
            `| **Confidence** | ${(evaluation.confidence * 100).toFixed(0)}% |`,
            `| **Iterations** | ${iterations.length} / ${issue.maxIterations} |`,
            `| **CI** | ${last?.ciResult ? CI_LABEL[last.ciResult] : 'unknown'} |`,
            issue.approvedBy ? `| **Code generation approved by** | ${inlineCode(issue.approvedBy)} |` : '',
            '',
            details('🔍 Evaluation', [
                '**Reasoning**', safe(evaluation.reasoning, 6000), '',
                '**Proposed approach**', safe(evaluation.proposedApproach, 4000), '',
                '**Affected files**', list(evaluation.affectedFiles.map(inlineCode)),
            ].join('\n')),
            details('🔎 Investigation', [
                `Files examined: ${investigation.filesExamined.length} · confidence ${(investigation.confidence * 100).toFixed(0)}%`, '',
                list(investigation.suggestedChanges.map((c) => `**${c.approach}** ${inlineCode(c.path)}: ${safe(c.description, 500)}`)),
                investigation.notes ? `\n**Notes**\n${safe(investigation.notes, 3000)}` : '',
            ].join('\n')),
            ...iterations.map((it) => details(`🔧 Iteration ${it.iteration} — ${it.ciResult ? CI_LABEL[it.ciResult] : 'not committed'}`, [
                list(it.filesChanged.map((f) => `${inlineCode(f.path)} (+${f.linesAdded}/-${f.linesRemoved})`)),
                '',
                `**Commit:** ${inlineCode(oneLine(it.commitMessage, 120))}${it.commitSha ? ` (${it.commitSha.slice(0, 8)})` : ''}`,
                '', '**Reasoning**', safe(it.reasoning, 3000),
                '', '**Self-review**', safe(it.selfReview, 3000),
                it.ciResult === 'failing' && it.ciLog ? `\n**CI log (tail)**\n\n${fence(truncate(it.ciLog, 4000))}` : '',
            ].join('\n'))),
            '',
            '> Generated by **Argus**. A human must review and merge — Argus never merges.',
        ];

        await this.post(forge, prNumber, sections.filter((s) => s !== '').join('\n'));
        this.logger.debug(`Posted transcript on PR #${prNumber}`);
    }

    async postCompetitiveAnalysis(forge: Forge, prNumber: number, analyses: PRAnalysis[]): Promise<void> {
        if (analyses.length === 0) { return; }
        const ranked = [...analyses].sort((a, b) => b.overallScore - a.overallScore);
        const pct = (n: number): string => `${(n * 100).toFixed(0)}%`;

        const content = [
            '## ⚔️ Competing PRs',
            '',
            `Found **${analyses.length}** PR(s) addressing this issue.`,
            '',
            ...ranked.map((pr, idx) => {
                const source = pr.isOurInstance ? '(ours)' : pr.isOtherArgus ? '(another Argus)' : '';
                return [
                    `${idx + 1}. **#${pr.prNumber}** by ${inlineCode(pr.author)} ${source} — **${pct(pr.overallScore)}**`,
                    `   correctness ${pct(pr.correctness)} · quality ${pct(pr.codeQuality)} · tests ${pct(pr.testCoverage)} · CI ${pr.ciPassing ? '✅' : '❌'}`,
                    `   strengths: ${safe(pr.strengths.join('; '), 400) || 'none'}`,
                    `   weaknesses: ${safe(pr.weaknesses.join('; '), 400) || 'none'}`,
                ].join('\n');
            }),
        ].join('\n');

        await this.post(forge, prNumber, content);
    }

    async postSynthesisPlan(forge: Forge, prNumber: number, synthesis: SynthesisCandidate): Promise<void> {
        const content = [
            '## 🧬 Combination plan',
            '',
            `A maintainer could combine elements of **${synthesis.sourcePRs.length}** PRs ` +
            `(projected score ${(synthesis.projectedScore * 100).toFixed(0)}%). Argus does not open the combined PR itself.`,
            '',
            ...synthesis.elementsFromEach.map((e) =>
                `**From #${e.prNumber}:**\n${list(e.elements.map((el) => safe(el, 300)))}\n_Reason: ${safe(e.reason, 300)}_`),
            '',
            '**Conflicts to resolve**',
            list(synthesis.conflictsToResolve.map((c) => safe(c, 300))),
        ].join('\n');

        await this.post(forge, prNumber, content);
    }

    private async post(forge: Forge, prNumber: number, content: string): Promise<void> {
        const { stamped, stamp } = this.stampManager.stampContent(truncate(content, MAX_COMMENT_CHARS));
        const comment = await forge.addPRComment(prNumber, stamped);
        if (comment?.id && !comment.id.startsWith('dry-run-')) {
            const repo = `${forge.platform}:${forge.owner}/${forge.repo}`;
            this.stampManager.recordPosted(stamp, artifactId(repo, 'comment', comment.id), repo);
        }
    }
}

function details(summary: string, body: string): string {
    return `<details><summary>${summary}</summary>\n\n${body}\n\n</details>\n`;
}

function list(items: string[]): string {
    return items.length ? items.map((i) => `- ${i}`).join('\n') : '_None_';
}

function fence(text: string): string {
    const longest = Math.max(2, ...(text.match(/`+/g) ?? []).map((m) => m.length));
    const f = '`'.repeat(longest + 1);
    return `${f}\n${text}\n${f}`;
}
